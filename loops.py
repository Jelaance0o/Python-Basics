# loop

for i in range(1, 6):
    print(i)


# Loop through a list

fruits = ["Apple", "Banana", "Mango", "Orange"]

for fruit in fruits:
    print(fruit)


# For loop with condition

for i in range(1, 11):
    if i % 2 == 0:
        print(i)


# While loop

i = 1

while i <= 5:
    print(i)
    i += 1


#  Nested loop

for i in range(1, 4):
    for j in range(1, 4):
        print(i, j)